"""
Тарифы — читаются из РЕАЛЬНОЙ таблицы `plans` бота, а не хардкодятся в коде.

v3 fix: раньше здесь был захардкоженный список PLANS (дни, фиксированные
рубли) — он физически не мог совпадать с тем, что видит бот, потому что
у бота тарифы per-host (host_name, months, price) и в МЕСЯЦАХ, а не в днях.
Расхождение цены между приложением и ботом = либо клиент переплачивает,
либо недоплачивает и не получает ключ. Теперь единственный источник
истины — таблица plans.

Бесплатный пробный тариф (trial) в реальной схеме нет — если он нужен как
бизнес-фича, его надо завести отдельной строкой в БД бота (напр. plan_id
зарезервированный под trial, price=0) либо явным флагом, а не изобретать
на бэкенде тариф, которого не существует в системе бота.

ВАЖНО (проверено по реальному backup БД, не предположение): во всех 4
строках `plans` поле `host_name = 'GLOBAL'` — то есть тарифы НЕ привязаны
к конкретному серверу, это просто варианты длительности (7/30/90/180 дней),
применимые к любому хосту. Сервер пользователь выбирает ОТДЕЛЬНО, на
экране серверов (`/v1/servers`). Поэтому `/v1/orders` принимает и
`plan_id`, и `host_name` как два независимых параметра (см. orders.py) —
раньше в v2 (и в первой версии v3-черновика) host сервера ошибочно
выводился ИЗ тарифа, что для этой схемы было бы неверно.
"""
from fastapi import APIRouter
from app.services import shop_db

router = APIRouter()


@router.get("")
async def list_plans():
    plans = await shop_db.get_plans()
    return [
        {
            "plan_id": p["plan_id"],
            "plan_name": p["plan_name"],
            "months": p["months"],
            "price_rub": p["price"],
        }
        for p in plans
    ]
